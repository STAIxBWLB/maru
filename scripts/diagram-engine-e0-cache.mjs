export const WASM_ASSET_OUTPUTS = Object.freeze([
  "src/lib/diagram/__generated__/engine-e0/maru_diagram_engine.js",
  "src/lib/diagram/__generated__/engine-e0/maru_diagram_engine_bg.wasm",
  "src/lib/diagram/__generated__/engine-geometry/maru_diagram_engine.js",
  "src/lib/diagram/__generated__/engine-geometry/maru_diagram_engine_bg.wasm",
  "src/lib/diagram/__generated__/engine-render/maru_diagram_engine.js",
  "src/lib/diagram/__generated__/engine-render/maru_diagram_engine_bg.wasm",
]);

const SHA256 = /^[a-f0-9]{64}$/;
const GIT_OBJECT_ID = /^[a-f0-9]{40}(?:[a-f0-9]{24})?$/;

export function isGeneratedUntrackedInput(path, targetDirectories = []) {
  const normalized = String(path).replaceAll("\\", "/").replace(/^\.\//, "");
  return normalized.split("/").includes("target")
    || /(?:^|\/)permissions\/(?:autogenerated|schemas)(?:\/|$)/.test(normalized)
    || targetDirectories.some((directory) => {
      const target = String(directory).replaceAll("\\", "/").replace(/^\.\//, "").replace(/\/+$/, "");
      return target !== "" && (normalized === target || normalized.startsWith(`${target}/`));
    });
}

export function hasDirtySdkInputs({ trackedChanges, untrackedFiles, targetDirectories = [] }) {
  return Boolean(trackedChanges)
    || untrackedFiles.some((path) => !isGeneratedUntrackedInput(path, targetDirectories));
}

export function makeWasmAssetsManifest({ originCommit, sdkTree, fingerprint, artifactHashes }) {
  if (typeof originCommit !== "string" || !GIT_OBJECT_ID.test(originCommit)
      || typeof sdkTree !== "string" || !GIT_OBJECT_ID.test(sdkTree)
      || typeof fingerprint !== "string" || !SHA256.test(fingerprint)) {
    throw new Error("Cannot record the WASM cache: origin commit, SDK tree, or build fingerprint is invalid.");
  }
  const artifacts = Object.fromEntries(WASM_ASSET_OUTPUTS.map((path) => [path, artifactHashes[path]]));
  if (Object.values(artifacts).some((hash) => typeof hash !== "string" || !SHA256.test(hash))) {
    throw new Error("Cannot record the WASM cache: one or more generated asset hashes are missing or invalid.");
  }
  return { version: 1, originCommit, sdkTree, fingerprint, artifacts };
}

/** Reuse only a clean SDK build whose exact inputs and all generated outputs match. */
export function canReuseWasmAssets({ manifest, sdkTree, fingerprint, clean, artifactHashes }) {
  if (clean !== true || !manifest || manifest.version !== 1
      || !GIT_OBJECT_ID.test(String(manifest.originCommit ?? ""))
      || !GIT_OBJECT_ID.test(String(manifest.sdkTree ?? ""))
      || !SHA256.test(String(manifest.fingerprint ?? ""))
      || manifest.sdkTree !== sdkTree || manifest.fingerprint !== fingerprint
      || !manifest.artifacts || typeof manifest.artifacts !== "object") return false;
  return WASM_ASSET_OUTPUTS.every((path) => {
    const expected = manifest.artifacts[path];
    const actual = artifactHashes?.[path];
    return typeof expected === "string" && SHA256.test(expected) && actual === expected;
  });
}
