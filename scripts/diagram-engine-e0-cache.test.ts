import { describe, expect, it } from "vitest";
import {
  canReuseWasmAssets,
  hasDirtySdkInputs,
  isGeneratedUntrackedInput,
  makeWasmAssetsManifest,
  WASM_ASSET_OUTPUTS,
} from "./diagram-engine-e0-cache.mjs";

const sdkTree = "a".repeat(40);
const originCommit = "b".repeat(40);
const fingerprint = "c".repeat(64);
const artifactHashes = Object.fromEntries(WASM_ASSET_OUTPUTS.map((path, index) => [path, String(index + 1).repeat(64)]));
const manifest = makeWasmAssetsManifest({ originCommit, sdkTree, fingerprint, artifactHashes });

describe("E0 generated WASM asset cache", () => {
  it("reuses only a clean matching SDK snapshot with every output hash present", () => {
    expect(canReuseWasmAssets({ manifest, sdkTree, fingerprint, clean: true, artifactHashes })).toBe(true);
    const tampered = { ...artifactHashes, [WASM_ASSET_OUTPUTS[2]!]: "0".repeat(64) };
    expect(canReuseWasmAssets({ manifest, sdkTree, fingerprint, clean: true, artifactHashes: tampered })).toBe(false);
    const missing = { ...artifactHashes };
    delete missing[WASM_ASSET_OUTPUTS[5]!];
    expect(canReuseWasmAssets({ manifest, sdkTree, fingerprint, clean: true, artifactHashes: missing })).toBe(false);
  });

  it("invalidates cache on source-tree or build-fingerprint changes", () => {
    expect(canReuseWasmAssets({ manifest, sdkTree: "d".repeat(40), fingerprint, clean: true, artifactHashes })).toBe(false);
    expect(canReuseWasmAssets({ manifest, sdkTree, fingerprint: "e".repeat(64), clean: true, artifactHashes })).toBe(false);
  });

  it("never reuses a clean manifest for dirty SDK inputs", () => {
    expect(canReuseWasmAssets({ manifest, sdkTree, fingerprint, clean: false, artifactHashes })).toBe(false);
    expect(hasDirtySdkInputs({ trackedChanges: " M src/lib.rs", untrackedFiles: [] })).toBe(true);
    expect(hasDirtySdkInputs({ trackedChanges: "", untrackedFiles: ["maru-diagram-engine/src/new_module.rs"] })).toBe(true);
  });

  it("ignores only generated permission and target directories among untracked paths", () => {
    expect(isGeneratedUntrackedInput("tauri-plugin-maru-diagram/permissions/autogenerated/commands/render.toml")).toBe(true);
    expect(isGeneratedUntrackedInput("tauri-plugin-maru-diagram/permissions/schemas/schema.json")).toBe(true);
    expect(isGeneratedUntrackedInput("maru-diagram-engine/target/debug/build/generated.rs")).toBe(true);
    expect(isGeneratedUntrackedInput("maru-diagram-engine/src/new.rs")).toBe(false);
    expect(hasDirtySdkInputs({
      trackedChanges: "",
      untrackedFiles: ["maru-diagram-engine/custom-build/cache/output.o"],
      targetDirectories: ["maru-diagram-engine/custom-build"],
    })).toBe(false);
    expect(hasDirtySdkInputs({
      trackedChanges: "",
      untrackedFiles: [
        "tauri-plugin-maru-diagram/permissions/autogenerated/commands/render.toml",
        "maru-diagram-engine/target/debug/build/generated.rs",
      ],
    })).toBe(false);
  });

  it("records the original build commit instead of inventing a later app origin", () => {
    const snapshot = makeWasmAssetsManifest({ originCommit, sdkTree, fingerprint, artifactHashes });
    expect(snapshot.originCommit).toBe(originCommit);
    expect(snapshot).not.toHaveProperty("checkedAtCommit");
    expect(canReuseWasmAssets({
      manifest: snapshot,
      sdkTree,
      fingerprint,
      clean: true,
      artifactHashes,
    })).toBe(true);
  });
});
